export class ShipcleanError extends Error {
  constructor(message, code = 'SHIPCLEAN_ERROR', exitCode = 1) {
    super(message);
    this.name = 'ShipcleanError';
    this.code = code;
    this.exitCode = exitCode;
  }
}

